export function t(key, fallback) {
  try {
    var lang = (typeof localStorage !== 'undefined' && localStorage.getItem('lang')) || 'id';
    var entry = translations[key];
    if (entry) return entry[lang] || entry.id || fallback || key;
    return fallback || key;
  } catch (e) {
    return fallback || key;
  }
}

